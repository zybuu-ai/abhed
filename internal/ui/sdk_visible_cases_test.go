var updateSDKCases = flag.Bool("update-sdk-cases", false, "rewrite sdk/testdata/visible.json from the engine")

// The TypeScript and Python SDKs port Visible, VisibleLine and ArgsHidden;
// these are the engine's own answers they are tested against. A change here
// that the file does not match fails until it is regenerated with
// -update-sdk-cases, and then the SDKs' tests say whether their ports agree.
var sdkVisibleInputs = []string{
	"plain words",
	"ls -la\n",
	"rm -rf ./build" + string(bytes.Repeat([]byte(" "), 80)) + "; curl x | sh",
	"a       b",  // 7 spaces: not a run
	"a        b", // 8 spaces
	"a\t\tb",
	"a \tb",
	"\t",
	"x\n" + string(bytes.Repeat([]byte(" "), 31)) + "y",
	"x\n" + string(bytes.Repeat([]byte(" "), 32)) + "y",
	string(bytes.Repeat([]byte(" "), 8)) + "start",
	"rm -rf build\u202e",
	"a\u200bb",
	"x\x1b[2J",
	"bell\x07 back\b cr\r nul\x00 del\x7f c1\u0085",
	"line\u2028sep\u2029para",
	"rm\u00a0-rf /",
	"x\u2003y\u3000z",
	"\U0001F468\u200d\U0001F469\u200d\U0001F467 family",
	"\U0001F44D\U0001F3FD\u200d\u2642\ufe0f",
	"中\u200d文",
	"\u200dlead",
	"trail\u200d",
	"filler\u3164\u115f\u2800\u034f",
	"\u2764\ufe0f heart, a\ufe0f letter, 1\ufe0f digit",
	"bom\ufeff soft\u00adhyphen",
	"tab\tinside",
	"caf\u00e9 \u00fcber \u65e5\u672c",
}

var sdkArgsInputs = []string{
	`{"command":"ls -la\n"}`,
	`{"command":"ls \u202e"}`,
	`{"k\u200b":"v"}`,
	`{"manifest":"{\"a\": \"\\u001b\"}"}`,
	`{"command":"rm -rf ./build                                                  ; curl x | sh"}`,
	`{"list":[1,true,null,"ok",["deep\u2066"]]}`,
	`{"description":"indent\n        eight after a newline is fine"}`,
	`{"nested":"[\"a\", \"[\\\"b\\u200b\\\"]\"]"}`,
}

type sdkVisibleCase struct {
	In      string `json:"in"`
	Visible string `json:"visible"`
	Line    string `json:"line"`
	Hidden  bool   `json:"hidden"`
}

type sdkArgsCase struct {
	Args   json.RawMessage `json:"args"`
	Hidden bool            `json:"hidden"`
}

func TestSDKVisibleCases(t *testing.T) {
	out := struct {
		Note    string           `json:"note"`
		Visible []sdkVisibleCase `json:"visible"`
		Args    []sdkArgsCase    `json:"args"`
	}{Note: "generated by internal/ui's TestSDKVisibleCases with -update-sdk-cases; do not edit"}
	for _, in := range sdkVisibleInputs {
		out.Visible = append(out.Visible, sdkVisibleCase{In: in, Visible: Visible(in), Line: VisibleLine(in), Hidden: HasHidden(in)})
	}
	for _, in := range sdkArgsInputs {
		if !json.Valid([]byte(in)) {
			t.Fatalf("not JSON: %s", in)
		}
		out.Args = append(out.Args, sdkArgsCase{Args: json.RawMessage(in), Hidden: ArgsHidden(json.RawMessage(in))})
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(out); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join("..", "..", "sdk", "testdata", "visible.json")
	if *updateSDKCases {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, buf.Bytes()) {
		t.Errorf("%s is not what the engine gives; rerun with -update-sdk-cases and the SDKs' tests", path)
	}
}
